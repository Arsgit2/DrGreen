def init_diseases():
    """Инициализация справочника болезней"""
    db = SessionLocal()
    
    try:
        # Проверяем, есть ли уже болезни в БД
        existing_count = db.query(Disease).count()
        
        if existing_count > 0:
            print(f"⚠️  В базе уже есть {existing_count} записей о болезнях")
            response = input("Очистить и заново заполнить? (y/n): ")
            if response.lower() != 'y':
                print("Отмена операции")
                return
            
            # Удаляем существующие записи
            db.query(Disease).delete()
            db.commit()
            print("✅ Существующие записи удалены")
        
        # Добавляем болезни
        for disease_data in diseases_data:
            disease = Disease(**disease_data)
            db.add(disease)
        
        db.commit()
        print(f"✅ Добавлено {len(diseases_data)} болезней в справочник")
        
        # Выводим список добавленных болезней
        diseases = db.query(Disease).all()
        print("\n📋 Болезни в справочнике:")
        for disease in diseases:
            print(f"  {disease.id}. {disease.name}")
        
    except Exception as e:
        print(f"❌ Ошибка: {e}")
        db.rollback()
    finally:
        db.close()

if __name__ == "__main__":
    print("🚀 Инициализация справочника болезней...")
    init_diseases()
    print("✅ Готово!")


